"""Towns -> El Hueco map: writes an hf_scene (pipeline/graphics/README.md). First used in el-hueco s3.
Usage: python pipeline/graphics/scenes/towns_map.py working/<slug>/graphics/towns_map.html
Unlabeled dots at the real positions of town seats around Medellín; gray lines draw in to one orange dot, El Hueco.
Coordinates: approximate municipal-seat lat/lon (2 decimals is plenty at this scale). No town is named on screen."""
import math
import sys
from pathlib import Path

HUECO = (6.248, -75.573)
TOWNS = {  # lat, lon
    "Bello": (6.337, -75.558), "Girardota": (6.378, -75.448), "Barbosa": (6.438, -75.331),
    "Guarne": (6.280, -75.444), "Rionegro": (6.155, -75.374), "Marinilla": (6.174, -75.336),
    "El Carmen de Viboral": (6.083, -75.336), "La Ceja": (6.031, -75.431), "El Peñol": (6.219, -75.243),
    "Guatapé": (6.233, -75.158), "Santo Domingo": (6.471, -75.165), "Santa Rosa de Osos": (6.646, -75.461),
    "San Jerónimo": (6.448, -75.727), "Sopetrán": (6.501, -75.743), "Santa Fe de Antioquia": (6.557, -75.828),
    "Caldas": (6.091, -75.636), "Amagá": (6.039, -75.703), "Titiribí": (6.062, -75.792),
    "Fredonia": (5.927, -75.674), "Abejorral": (5.789, -75.428), "Sonsón": (5.712, -75.311),
    "Jericó": (5.791, -75.785), "Andes": (5.657, -75.880), "Jardín": (5.598, -75.819),
}
VB_W, VB_H, S = 760, 900, 640          # panel viewBox; pixels per degree


def xy(lat, lon):
    return 112 + (lon + 75.90) * S, 150 + (6.70 - lat) * S


hx, hy = xy(*HUECO)
lines, dots = [], []
order = sorted(TOWNS.items(), key=lambda kv: -math.dist(xy(*kv[1]), (hx, hy)))   # far towns start first
for i, (name, ll) in enumerate(order):
    x, y = xy(*ll)
    L = math.dist((x, y), (hx, hy))
    lines.append(f'<line class="ln" data-i="{i}" x1="{x:.1f}" y1="{y:.1f}" x2="{hx:.1f}" y2="{hy:.1f}" '
                 f'stroke-dasharray="{L:.1f}" stroke-dashoffset="{L:.1f}"><title>{name}</title></line>')
    dots.append(f'<circle class="dt" cx="{x:.1f}" cy="{y:.1f}" r="9"/>')

html = f"""<!-- el-hueco s3: towns around Medellín -> El Hueco. Generated by pipeline/graphics/scenes/towns_map.py; edit that, not this. -->
<template>
  <style>
    {{{{brand_css}}}}
    #{{{{id}}}} {{ position: absolute; inset: 0; }}
    #{{{{id}}}} .tm-panel {{ position: absolute; left: 160px; top: 300px; width: {VB_W}px; height: {VB_H}px;
      background: var(--mb-cream); border-radius: 12px; overflow: hidden; }}
    #{{{{id}}}} .tm-eyebrow {{ position: absolute; left: 0; right: 0; top: 46px; text-align: center; font-size: 30px; }}
    #{{{{id}}}} svg {{ position: absolute; inset: 0; }}
    #{{{{id}}}} .ln {{ stroke: var(--mb-gray); stroke-width: 4; stroke-linecap: round; }}
    #{{{{id}}}} .dt {{ fill: var(--mb-ink); }}
    #{{{{id}}}} .hb {{ fill: var(--mb-orange); }}
    #{{{{id}}}} .hr {{ opacity: 0; fill: none; stroke: var(--mb-orange); stroke-width: 4; }}
    #{{{{id}}}} .tm-label {{ position: absolute; right: {VB_W - hx + 32:.0f}px; top: {hy - 34:.0f}px; padding: 8px 16px;
      background: var(--mb-ink); color: var(--mb-white); border-radius: 8px; font-size: 40px; line-height: 52px; }}
  </style>
  <div id="{{{{id}}}}" data-composition-id="{{{{id}}}}" data-width="1080" data-height="1920">
    <div id="{{{{id}}}}-panel" class="tm-panel">
      <div class="tm-eyebrow mb-eyebrow">ANTIOQUIA · COLOMBIA</div>
      <svg viewBox="0 0 {VB_W} {VB_H}" width="{VB_W}" height="{VB_H}">
        {"".join(lines)}
        {"".join(dots)}
        <circle id="{{{{id}}}}-ring" class="hr" opacity="0" cx="{hx:.1f}" cy="{hy:.1f}" r="20"/>
        <circle id="{{{{id}}}}-hub" class="hb" cx="{hx:.1f}" cy="{hy:.1f}" r="20"/>
      </svg>
      <div id="{{{{id}}}}-label" class="tm-label mb-xb">EL HUECO</div>
    </div>
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
    const root = "#{{{{id}}}}";
    // in: the panel's mask opens left to right (same move as the title card), 0.3 s ease-out
    tl.fromTo(root + "-panel", {{ clipPath: "inset(0% 100% 0% 0% round 12px)", y: 16 }},
      {{ clipPath: "inset(0% 0% 0% 0% round 12px)", y: 0, duration: 0.3, ease: "expo.out" }}, 0);
    tl.from(root + "-hub", {{ scale: 0, transformOrigin: "50% 50%", duration: 0.35, ease: "expo.out" }}, 0.2);
    tl.from(root + "-label", {{ opacity: 0, x: -12, duration: 0.3, ease: "expo.out" }}, 0.3);
    tl.from(root + " .dt", {{ opacity: 0, duration: 0.3, ease: "power2.out", stagger: 0.025 }}, 0.3);
    // the towns' lines draw in to El Hueco, farthest first, then the hub ring pulses once
    tl.to(root + " .ln", {{ strokeDashoffset: 0, duration: 0.7, ease: "power3.out", stagger: 0.04 }}, 0.55);
    tl.to(root + "-ring", {{ opacity: 0.9, duration: 0.01 }}, 1.9);
    tl.to(root + "-ring", {{ scale: 2.6, opacity: 0, transformOrigin: "50% 50%", duration: 0.6, ease: "expo.out" }}, 1.91);
    // out: the mask closes back to the left, 0.2 s
    tl.to(root + "-panel", {{ clipPath: "inset(0% 100% 0% 0% round 12px)", duration: 0.2, ease: "power3.in" }},
      Math.max({{{{dur}}}} - 0.21, 2.5));
    window.__timelines["{{{{id}}}}"] = tl;
  </script>
</template>
"""
out = Path(sys.argv[1] if len(sys.argv) > 1 else "working/el-hueco/graphics/towns_map.html")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(html, encoding="utf-8")
print("wrote", out, f"hub at ({hx:.0f},{hy:.0f}) in panel")
